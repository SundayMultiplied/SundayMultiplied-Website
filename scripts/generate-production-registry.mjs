import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const churchesDir = path.join(root, "churches");
const outputDir = path.join(root, "worker", "generated");
const registryFile = path.join(outputDir, "church-registry.ts");
const assetMapFile = path.join(outputDir, "church-assets.ts");
const publicResourcesDir = path.join(root, "public", "resources");
const defaultBaseCssUrl = "/resources/_shared/sunday-multiplied-base.css";
const allowedResources = new Set(["monday", "group", "family"]);

function repositoryPath(value) {
  const normalized = String(value || "").trim().replaceAll("\\", "/");
  if (!normalized || normalized.startsWith("/") || normalized.includes("..")) return "";
  return normalized;
}
function publishedChurchCss(source) {
  return source.replace(/^\s*@import\s+url\([^\n]*sunday-multiplied-base\.css[^\n]*\);?\s*/gim, "").trimStart();
}

const entries = await readdir(churchesDir, { withFileTypes: true });
const churches = [];
const primaryLogoKeys = {};

for (const entry of entries) {
  if (!entry.isDirectory()) continue;
  const manifestPath = path.join(churchesDir, entry.name, "church.json");
  let manifest;
  try { manifest = JSON.parse(await readFile(manifestPath, "utf8")); } catch { continue; }

  const slug = String(manifest?.church?.slug || "").trim();
  const name = String(manifest?.church?.name || "").trim();
  const resources = Array.isArray(manifest?.resources) ? manifest.resources.filter((item) => allowedResources.has(item)) : [];
  const brand = manifest?.brand || {};
  const stylesheetPath = repositoryPath(brand.stylesheet);
  const primaryAsset = Array.isArray(brand.assets) ? brand.assets.find((asset) => asset?.kind === "primary" && asset?.r2Key) : undefined;
  const hasPrimaryLogo = Boolean(primaryAsset || brand.logoUrl);

  if (!slug || !name || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug) || resources.length === 0 || !stylesheetPath) continue;

  const sourceStylesheet = path.join(root, stylesheetPath);
  const publicChurchDir = path.join(publicResourcesDir, slug);
  const publicStylesheetFile = path.join(publicChurchDir, "church.css");
  await mkdir(publicChurchDir, { recursive: true });
  try {
    const sourceCss = await readFile(sourceStylesheet, "utf8");
    const overridesPath = path.join(path.dirname(sourceStylesheet), "overrides.css");
    let overridesCss = "";
    try { overridesCss = await readFile(overridesPath, "utf8"); } catch {}
    const publishedCss = [publishedChurchCss(sourceCss), publishedChurchCss(overridesCss)].filter(Boolean).join("\n\n");
    await writeFile(publicStylesheetFile, publishedCss, "utf8");
  } catch (error) {
    console.warn(`Skipping ${slug}: unable to publish stylesheet ${stylesheetPath}.`, error);
    continue;
  }

  const baseCssUrl = String(brand.sharedStylesheet || defaultBaseCssUrl).trim() || defaultBaseCssUrl;
  const cssUrl = String(brand.publicStylesheet || `/resources/${slug}/church.css`).trim();
  const logoUrl = hasPrimaryLogo ? String(brand.logoUrl || primaryAsset?.publicUrl || `/api/resource-assets/${slug}/logo`).trim() : "";

  churches.push({ slug, name, resources, baseCssUrl, cssUrl, logoUrl });
  if (primaryAsset) primaryLogoKeys[slug] = String(primaryAsset.r2Key).trim();
}

churches.sort((a, b) => a.name.localeCompare(b.name));
await mkdir(outputDir, { recursive: true });
await writeFile(registryFile, `// AUTO-GENERATED by scripts/generate-production-registry.mjs. Do not edit manually.\nexport const PRODUCTION_CHURCHES = ${JSON.stringify(churches, null, 2)};\n`, "utf8");
await writeFile(assetMapFile, `// AUTO-GENERATED by scripts/generate-production-registry.mjs. Do not edit manually.\nexport const PRIMARY_LOGO_R2_KEYS: Record<string, string> = ${JSON.stringify(primaryLogoKeys, null, 2)};\n`, "utf8");
console.log(`Generated production registry with ${churches.length} church(es): ${churches.map((church) => church.slug).join(", ")}.`);

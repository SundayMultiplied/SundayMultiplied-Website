import type { RepositoryFile } from "./repo-files";

type GitHubConfig = {
  owner: string;
  repo: string;
  baseBranch: string;
  token: string;
};

export type BinaryRepositoryFile = { path: string; base64: string };
type PullRequestFile = RepositoryFile | BinaryRepositoryFile;

async function github<T>(config: GitHubConfig, path: string, init: RequestInit = {}): Promise<T> {
  const response = await fetch(`https://api.github.com${path}`, {
    ...init,
    headers: {
      accept: "application/vnd.github+json",
      authorization: `Bearer ${config.token}`,
      "content-type": "application/json",
      "user-agent": "SundayMultipliedOnboarding/1.0",
      "x-github-api-version": "2022-11-28",
      ...init.headers,
    },
  });
  if (!response.ok) {
    const detail = (await response.text()).slice(0, 500);
    throw new Error(`GitHub ${response.status}: ${detail}`);
  }
  return (await response.json()) as T;
}

export async function createOnboardingPullRequest(
  config: GitHubConfig,
  slug: string,
  churchName: string,
  files: PullRequestFile[],
): Promise<{ branch: string; pullRequestUrl: string }> {
  const ref = await github<{ object: { sha: string } }>(
    config,
    `/repos/${config.owner}/${config.repo}/git/ref/heads/${encodeURIComponent(config.baseBranch)}`,
  );
  const baseCommit = await github<{ tree: { sha: string } }>(
    config,
    `/repos/${config.owner}/${config.repo}/git/commits/${ref.object.sha}`,
  );

  const treeEntries: Array<Record<string, string>> = [];
  for (const file of files) {
    if ("base64" in file) {
      const blob = await github<{ sha: string }>(config, `/repos/${config.owner}/${config.repo}/git/blobs`, {
        method: "POST",
        body: JSON.stringify({ content: file.base64, encoding: "base64" }),
      });
      treeEntries.push({ path: file.path, mode: "100644", type: "blob", sha: blob.sha });
    } else {
      treeEntries.push({ path: file.path, mode: "100644", type: "blob", content: file.content });
    }
  }

  const tree = await github<{ sha: string }>(config, `/repos/${config.owner}/${config.repo}/git/trees`, {
    method: "POST",
    body: JSON.stringify({ base_tree: baseCommit.tree.sha, tree: treeEntries }),
  });
  const commit = await github<{ sha: string }>(config, `/repos/${config.owner}/${config.repo}/git/commits`, {
    method: "POST",
    body: JSON.stringify({
      message: `onboard(${slug}): add church workspace`,
      tree: tree.sha,
      parents: [ref.object.sha],
    }),
  });
  const branch = `onboard/${slug}-${Date.now()}`;
  await github(config, `/repos/${config.owner}/${config.repo}/git/refs`, {
    method: "POST",
    body: JSON.stringify({ ref: `refs/heads/${branch}`, sha: commit.sha }),
  });
  const pull = await github<{ html_url: string }>(config, `/repos/${config.owner}/${config.repo}/pulls`, {
    method: "POST",
    body: JSON.stringify({
      title: `Onboard ${churchName}`,
      head: branch,
      base: config.baseBranch,
      body: `## Church onboarding\n\nGenerated by the Sunday Multiplied onboarding agent.\n\n- Adds the church manifest and source URLs\n- Adds the client CSS override\n- Publishes the primary logo at a permanent resource URL\n- Creates the weekly resource directory\n- Configures the shared approval dashboard\n\nReviewer contact details remain in the private onboarding agent state and are intentionally excluded from this repository. Confirm brand assets before merging.`,
    }),
  });
  return { branch, pullRequestUrl: pull.html_url };
}
